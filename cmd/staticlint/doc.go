// Command staticlint — мультичекер для проекта metrics.
//
// # Назначение
//
// staticlint построен на фреймворке go/analysis
// Он включает в себя:
//
//   - стандартные анализаторы из golang.org/x/tools/go/analysis/passes;
//   - всех анализаторов класса SA пакета staticcheck.io;,
//     упрощения класса S (simple) и стилевые проверки класса ST
//     (stylecheck);
//   - публичные анализаторы (nilerr, predeclared);
//   - собственный анализатор osExit, запрещающий прямой вызов
//     os.Exit внутри файлов main
//
// # Запуск
//
// Сборка bin-файла и его запуск:
//
//	go build -o mycheck ./cmd/staticlint
//	./mycheck ./...
//
// Полный список зарегистрированных флагов:
//
//	./mycheck help
//
// # Стандартные анализаторы
//
// Стандартные passes:
//
//   - appends — находит вызовы append без аргументов-значений, которые
//     молча теряют элементы.
//   - atomicalign — сообщает о полях структур, к которым применяются
//     64-битные atomic-операции без выравнивания (актуально для
//     32-битных платформ).
//   - deepequalerrors — предупреждает об использовании
//     reflect.DeepEqual на значениях типа error (не учитывает
//     обёрнутые ошибки).
//   - defers — типичные ошибки с defer: time.Sleep внутри defer,
//     defer в цикле и т.п.
//   - directive — проверяет синтаксис директив //go: в исходниках.
//   - fieldalignment — сообщает о структурах, поля которых можно
//     переставить для экономии памяти за счёт выравнивания.
//   - framepointer — проверяет, что ассемблерный код не портит
//     frame pointer.
//   - gofixdirective — проверяет, что директива //go:fix применена
//     только к объявлениям функций.
//   - hostport — предупреждает о склейке host:port через fmt.Sprintf.
//   - httpmux — сообщает об устаревших шаблонах настройки http.ServeMux.
//   - loopclosure — находит ссылки на переменные цикла из вложенных
//     функций/горутин, переживающих итерацию.
//   - nilness — на основе SSA находит невозможные сравнения с nil и
//     избыточные nil-проверки.
//   - reflectvaluecompare — предупреждает о сравнении reflect.Value
//     через == (нужен .Equal).
//   - scannererr — сообщает о непроверенном bufio.Scanner.Err.
//   - shadow — находит затенение переменных, которое может скрыть
//     баг.
//   - sigchanyzer — сообщает о небуферизованном канале для
//     os.Signal (доставка сигнала может блокироваться).
//   - slog — проверяет типичные ошибки при работе с log/slog.
//   - sortslice — сообщает о sort.Slice с не-слайсом в первом
//     аргументе.
//   - sqlrowserr — сообщает о непроверенном sql.Rows.Err.
//   - stdversion — предупреждает об использовании символов
//     стандартной библиотеки новее версии Go из go.mod.
//   - testinggoroutine — находит вызовы t.Fatal/t.FailNow из
//     не-тестовых горутин.
//   - timeformat — сообщает о некорректных layout-строках в
//     time.Format / time.Parse.
//   - unusedwrite — находит записи в переменные/поля, которые
//     никогда не читаются.
//   - usesgenerics — подсказывает места, где можно применить
//     дженерики.
//   - waitgroup — находит неправильное использование sync.WaitGroup
//     (например, Add из горутины, которую ждут).
//
// # Анализаторы Staticcheck
//
// staticcheck (класс SA) — bug-проверки: разыменование nil, неверная
// работа с блокировками, бесполезные присваивания и т.п. Полный список
// — https://staticcheck.io/docs/checks#SA.
//
// simple (класс S) — предложения по упрощению корректного кода, e.g.
// S1000, S1002 и др.
//
// stylecheck (класс ST) — стилевые проверки: именование, оформление
// doc-комментариев, формат ошибок и т.п.
//
// # Публичные анализаторы
//
// nilerr — находит паттерны "if err != nil { return nil }", где
// ненулевая ошибка молча проглатывается.
//
// predeclared — находит затенение предобъявленных идентификаторов Go
// (len, cap, new, copy и т.п.).
//
// # Собственный анализатор osExit
//
// osExit запрещает прямые вызовы os.Exit внутри main.
